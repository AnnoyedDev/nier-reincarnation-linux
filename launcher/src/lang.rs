#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn french_follows_the_code() {
        assert_eq!(trf("{} of {}", &[&1, &"x"]), "1 of x");
        let code = [include_str!("ui.rs"), include_str!("main.rs"), include_str!("settings.rs"),
                    include_str!("../../tools/setup_game.py")].concat();
        let mut seen = std::collections::HashSet::new();
        for (en, fr) in FR {
            assert!(seen.insert(en), "twice in the table: {en}");
            assert_eq!(en.matches("{}").count(), fr.matches("{}").count(), "blanks differ: {en}");
            assert!(code.contains(&en.replace('"', "\\\"")), "not in the code: {en}");
        }
        set("fr");
        assert_eq!(tr("Settings"), "Paramètres");
        assert_eq!(tr("a save's name"), "a save's name");
        assert_eq!(trf("Save {}", &[&2]), "Sauvegarde 2");
        set("en");
        assert_eq!(tr("Settings"), "Settings");
    }
}
