use std::collections::HashMap;
use std::fmt::Display;
use std::sync::atomic::{AtomicBool, Ordering};
use std::sync::OnceLock;

static FRENCH: AtomicBool = AtomicBool::new(false);

pub fn set(code: &str) {
    let fr = match code {
        "fr" => true,
        "en" => false,
        _ => ["LC_ALL", "LC_MESSAGES", "LANG"].iter().find_map(|k| std::env::var(k).ok().filter(|v| !v.is_empty()))
            .is_some_and(|v| v.starts_with("fr")),
    };
    FRENCH.store(fr, Ordering::Relaxed);
}

pub fn tr(text: &str) -> &str {
    if !FRENCH.load(Ordering::Relaxed) {
        return text;
    }
    static MAP: OnceLock<HashMap<&str, &str>> = OnceLock::new();
    MAP.get_or_init(|| FR.iter().copied().collect()).get(text).copied().unwrap_or(text)
}

pub fn trf(text: &str, args: &[&dyn Display]) -> String {
    let mut parts = tr(text).split("{}");
    let mut out = parts.next().unwrap_or_default().to_string();
    for (part, arg) in parts.zip(args) {
        out += &format!("{arg}{part}");
    }
    out
}

